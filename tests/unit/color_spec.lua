local Color = require("ascii-ui.color")
local Segment = require("ascii-ui.buffer.segment")
local eq = require("tests.assertions").eq

describe("Color", function()
	describe("new", function()
		it("creates color from table with fg", function()
			local c = Color.new({ fg = "#ff0000" })
			eq("#ff0000", c.fg)
			eq(nil, c.bg)
		end)

		it("creates color from table with bg", function()
			local c = Color.new({ bg = "#00ff00" })
			eq(nil, c.fg)
			eq("#00ff00", c.bg)
		end)

		it("creates color from table with fg and bg", function()
			local c = Color.new({ fg = "#ff0000", bg = "#0000ff" })
			eq("#ff0000", c.fg)
			eq("#0000ff", c.bg)
		end)

		it("creates color from string shorthand (treated as fg)", function()
			local c = Color.new("#ff0000")
			eq("#ff0000", c.fg)
			eq(nil, c.bg)
		end)

		it("normalizes hex to lowercase", function()
			local c = Color.new("#FF00AA")
			eq("#ff00aa", c.fg)
		end)

		it("adds # prefix if missing", function()
			local c = Color.new("ff00aa")
			eq("#ff00aa", c.fg)
		end)

		it("expands 3-char hex to 6-char", function()
			local c = Color.new("#f0a")
			eq("#ff00aa", c.fg)
		end)

		it("caches identical colors", function()
			local c1 = Color.new("#ff0000")
			local c2 = Color.new("#ff0000")
			assert(c1 == c2) -- same instance
		end)

		it("caches table and string with same fg", function()
			local c1 = Color.new("#ff0000")
			local c2 = Color.new({ fg = "#ff0000" })
			assert(c1 == c2) -- same instance
		end)

		it("returns same instance if passed a Color", function()
			local c1 = Color.new("#ff0000")
			local c2 = Color.new(c1)
			assert(c1 == c2)
		end)

		it("errors on invalid input type", function()
			MiniTest.expect.error(function()
				Color.new(123)
			end)
		end)
	end)

	describe("to_hl_group", function()
		it("creates a highlight group name", function()
			local c = Color.new({ fg = "#ff0000", bg = "#00ff00" })
			local hl = c:to_hl_group()
			assert(hl:find("AsciiUI_fg"))
			assert(hl:find("ff0000"))
			assert(hl:find("00ff00"))
		end)

		it("caches highlight groups", function()
			local c1 = Color.new("#ff0000")
			local c2 = Color.new("#ff0000")
			eq(c1:to_hl_group(), c2:to_hl_group())
		end)

		it("handles fg only", function()
			local c = Color.new({ fg = "#ff0000" })
			local hl = c:to_hl_group()
			assert(hl:find("NONE"))
		end)

		it("handles bg only", function()
			local c = Color.new({ bg = "#00ff00" })
			local hl = c:to_hl_group()
			assert(hl:find("NONE"))
		end)
	end)

	describe("to_ansi", function()
		it("returns fg ANSI code", function()
			local c = Color.new({ fg = "#ff0000" })
			local ansi = c:to_ansi()
			-- ESC[38;2;255;0;0m
			assert(ansi:find("\027%[38;2;255;0;0m"))
		end)

		it("returns bg ANSI code", function()
			local c = Color.new({ bg = "#00ff00" })
			local ansi = c:to_ansi()
			-- ESC[48;2;0;255;0m
			assert(ansi:find("\027%[48;2;0;255;0m"))
		end)

		it("returns both fg and bg ANSI codes", function()
			local c = Color.new({ fg = "#ff0000", bg = "#0000ff" })
			local ansi = c:to_ansi()
			assert(ansi:find("\027%[38;2;255;0;0m"))
			assert(ansi:find("\027%[48;2;0;0;255m"))
		end)

		it("returns empty string for empty color", function()
			local c = Color.new({})
			eq("", c:to_ansi())
		end)
	end)

	describe("is_empty", function()
		it("returns true when neither fg nor bg set", function()
			local c = Color.new({})
			assert(c:is_empty())
		end)

		it("returns false when fg set", function()
			local c = Color.new({ fg = "#ff0000" })
			assert(not (c:is_empty()))
		end)

		it("returns false when bg set", function()
			local c = Color.new({ bg = "#00ff00" })
			assert(not (c:is_empty()))
		end)

		it("returns false when both set", function()
			local c = Color.new({ fg = "#ff0000", bg = "#00ff00" })
			assert(not (c:is_empty()))
		end)
	end)

	describe("is_color", function()
		it("returns true for Color instance", function()
			local c = Color.new("#ff0000")
			assert(Color.is_color(c))
		end)

		it("returns false for plain table", function()
			assert(not (Color.is_color({ fg = "#ff0000" })))
		end)

		it("returns false for nil", function()
			assert(not (Color.is_color(nil)))
		end)

		it("returns false for string", function()
			assert(not (Color.is_color("#ff0000")))
		end)
	end)

	describe("from_hsl", function()
		it("creates red from HSL(0, 100, 50)", function()
			local c = Color.from_hsl(0, 100, 50)
			eq("#ff0000", c.fg)
		end)

		it("creates green from HSL(120, 100, 50)", function()
			local c = Color.from_hsl(120, 100, 50)
			eq("#00ff00", c.fg)
		end)

		it("creates blue from HSL(240, 100, 50)", function()
			local c = Color.from_hsl(240, 100, 50)
			eq("#0000ff", c.fg)
		end)

		it("creates white from HSL(0, 0, 100)", function()
			local c = Color.from_hsl(0, 0, 100)
			eq("#ffffff", c.fg)
		end)

		it("creates black from HSL(0, 0, 0)", function()
			local c = Color.from_hsl(0, 0, 0)
			eq("#000000", c.fg)
		end)

		it("creates gray from HSL(0, 0, 50)", function()
			local c = Color.from_hsl(0, 0, 50)
			eq("#808080", c.fg)
		end)

		it("clamps hue to 0-360", function()
			local c1 = Color.from_hsl(-10, 100, 50)
			local c2 = Color.from_hsl(0, 100, 50)
			eq(c1.fg, c2.fg)
		end)

		it("clamps hue above 360", function()
			local c1 = Color.from_hsl(400, 100, 50)
			local c2 = Color.from_hsl(360, 100, 50)
			eq(c1.fg, c2.fg)
		end)

		it("clamps saturation to 0-100", function()
			local c1 = Color.from_hsl(0, -10, 50)
			local c2 = Color.from_hsl(0, 0, 50)
			eq(c1.fg, c2.fg)

			local c3 = Color.from_hsl(0, 150, 50)
			local c4 = Color.from_hsl(0, 100, 50)
			eq(c3.fg, c4.fg)
		end)

		it("clamps lightness to 0-100", function()
			local c1 = Color.from_hsl(0, 100, -10)
			local c2 = Color.from_hsl(0, 100, 0)
			eq(c1.fg, c2.fg)

			local c3 = Color.from_hsl(0, 100, 150)
			local c4 = Color.from_hsl(0, 100, 100)
			eq(c3.fg, c4.fg)
		end)

		it("creates cyan from HSL(180, 100, 50)", function()
			local c = Color.from_hsl(180, 100, 50)
			eq("#00ffff", c.fg)
		end)

		it("creates yellow from HSL(60, 100, 50)", function()
			local c = Color.from_hsl(60, 100, 50)
			eq("#ffff00", c.fg)
		end)

		it("creates magenta from HSL(300, 100, 50)", function()
			local c = Color.from_hsl(300, 100, 50)
			eq("#ff00ff", c.fg)
		end)
	end)

	describe("to_hsl", function()
		it("converts red to HSL", function()
			local c = Color.new("#ff0000")
			local h, s, l = c:to_hsl()
			eq(0, h)
			eq(100, s)
			eq(50, l)
		end)

		it("converts green to HSL", function()
			local c = Color.new("#00ff00")
			local h, s, l = c:to_hsl()
			eq(120, h)
			eq(100, s)
			eq(50, l)
		end)

		it("converts blue to HSL", function()
			local c = Color.new("#0000ff")
			local h, s, l = c:to_hsl()
			eq(240, h)
			eq(100, s)
			eq(50, l)
		end)

		it("converts white to HSL", function()
			local c = Color.new("#ffffff")
			local h, s, l = c:to_hsl()
			eq(0, h)
			eq(0, s)
			eq(100, l)
		end)

		it("converts black to HSL", function()
			local c = Color.new("#000000")
			local h, s, l = c:to_hsl()
			eq(0, h)
			eq(0, s)
			eq(0, l)
		end)

		it("returns nil when fg not set", function()
			local c = Color.new({ bg = "#ff0000" })
			local h, s, l = c:to_hsl()
			eq(nil, h)
			eq(nil, s)
			eq(nil, l)
		end)
	end)

	describe("lighten", function()
		it("increases lightness", function()
			local c = Color.new("#ff0000")
			local lighter = c:lighten(20)
			local _, _, l = lighter:to_hsl()
			eq(70, l)
		end)

		it("clamps to 100", function()
			local c = Color.new("#ff0000")
			local lighter = c:lighten(100)
			local _, _, l = lighter:to_hsl()
			eq(100, l)
		end)

		it("returns same color when fg not set", function()
			local c = Color.new({ bg = "#ff0000" })
			local lighter = c:lighten(20)
			assert(c == lighter)
		end)
	end)

	describe("darken", function()
		it("decreases lightness", function()
			local c = Color.new("#ff0000")
			local darker = c:darken(20)
			local _, _, l = darker:to_hsl()
			eq(30, l)
		end)

		it("clamps to 0", function()
			local c = Color.new("#ff0000")
			local darker = c:darken(100)
			local _, _, l = darker:to_hsl()
			eq(0, l)
		end)

		it("returns same color when fg not set", function()
			local c = Color.new({ bg = "#ff0000" })
			local darker = c:darken(20)
			assert(c == darker)
		end)
	end)

	describe("complement", function()
		it("returns complement color", function()
			local c = Color.new("#ff0000")
			local comp = c:complement()
			local h, s, l = comp:to_hsl()
			eq(180, h)
			eq(100, s)
			eq(50, l)
		end)

		it("complement of complement is original", function()
			local c = Color.new("#ff0000")
			local comp = c:complement()
			local double_comp = comp:complement()
			eq(c.fg, double_comp.fg)
		end)

		it("returns same color when fg not set", function()
			local c = Color.new({ bg = "#ff0000" })
			local comp = c:complement()
			assert(c == comp)
		end)
	end)

	describe("saturate", function()
		it("increases saturation", function()
			local c = Color.from_hsl(0, 50, 50)
			local saturated = c:saturate(30)
			local _, s, _ = saturated:to_hsl()
			eq(80, s)
		end)

		it("clamps to 100", function()
			local c = Color.from_hsl(0, 80, 50)
			local saturated = c:saturate(50)
			local _, s, _ = saturated:to_hsl()
			eq(100, s)
		end)

		it("returns same color when fg not set", function()
			local c = Color.new({ bg = "#ff0000" })
			local saturated = c:saturate(20)
			assert(c == saturated)
		end)
	end)

	describe("desaturate", function()
		it("decreases saturation", function()
			local c = Color.from_hsl(0, 80, 50)
			local desaturated = c:desaturate(30)
			local _, s, _ = desaturated:to_hsl()
			eq(50, s)
		end)

		it("clamps to 0", function()
			local c = Color.from_hsl(0, 30, 50)
			local desaturated = c:desaturate(50)
			local _, s, _ = desaturated:to_hsl()
			eq(0, s)
		end)

		it("returns same color when fg not set", function()
			local c = Color.new({ bg = "#ff0000" })
			local desaturated = c:desaturate(20)
			assert(c == desaturated)
		end)
	end)
end)

describe("Segment color shorthand", function()
	it("accepts string color as fg shorthand", function()
		local seg = Segment:new({ content = "test", color = "#ff0000" })
		eq({ fg = "#ff0000" }, seg.color)
	end)

	it("accepts table color", function()
		local seg = Segment:new({ content = "test", color = { fg = "#ff0000", bg = "#00ff00" } })
		eq({ fg = "#ff0000", bg = "#00ff00" }, seg.color)
	end)

	it("accepts Color instance", function()
		local c = Color.new("#ff0000")
		local seg = Segment:new({ content = "test", color = c })
		assert(Color.is_color(seg.color))
		eq("#ff0000", seg.color.fg)
	end)

	it("handles nil color", function()
		local seg = Segment:new({ content = "test" })
		eq(nil, seg.color)
	end)

	it("is_colored works with string shorthand", function()
		local seg = Segment:new({ content = "test", color = "#ff0000" })
		assert(seg:is_colored())
	end)

	it("is_colored works with table", function()
		local seg = Segment:new({ content = "test", color = { fg = "#ff0000" } })
		assert(seg:is_colored())
	end)

	it("is_colored works with Color instance", function()
		local c = Color.new("#ff0000")
		local seg = Segment:new({ content = "test", color = c })
		assert(seg:is_colored())
	end)
end)
